-- init.sql
-- RAGアーキテクチャに特化した最新の初期化スキーマ

-- 1. pgvector 拡張機能の有効化
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. articles テーブル作成
CREATE TABLE IF NOT EXISTS public.articles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  url text NOT NULL UNIQUE,
  summary text,
  is_read boolean NOT NULL DEFAULT false,
  save_type text CHECK (save_type IS NULL OR save_type IN ('later', 'important', 'done')),
  user_note text,
  embedding vector(1536),
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. インデックス作成
CREATE INDEX IF NOT EXISTS articles_url_idx ON public.articles (url);
CREATE INDEX IF NOT EXISTS articles_created_at_idx ON public.articles (created_at DESC);

-- 4. RAG類似度検索用関数
CREATE OR REPLACE FUNCTION public.match_articles(
  query_embedding vector(1536),
  match_threshold double precision DEFAULT 0.0,
  match_count integer DEFAULT 10
)
RETURNS TABLE (
  id bigint,
  title text,
  url text,
  summary text,
  similarity double precision
)
LANGUAGE sql
STABLE
AS $$
  SELECT
    a.id,
    a.title,
    a.url,
    a.summary,
    (1 - (a.embedding <=> query_embedding))::double precision AS similarity
  FROM public.articles AS a
  WHERE a.embedding IS NOT NULL
    AND 1 - (a.embedding <=> query_embedding) >= match_threshold
  ORDER BY a.embedding <=> query_embedding
  LIMIT GREATEST(match_count, 1);
$$;
